const DEFAULT_CHAR_W = 62;
const REFERENCE_FONT_SIZE = 100;

function charWidth(char, bold) {
    const table = bold ? BOLD_CHAR_W : REGULAR_CHAR_W;
    const value = table[char];
    return typeof value === 'number' ? value : DEFAULT_CHAR_W;
}

function measureCanvasText(text, fontSize, bold) {
    const size = Number(fontSize);
    if (!Number.isFinite(size) || size <= 0) return 0;
    let units = 0;
    for (const char of String(text || '')) units += charWidth(char, bold);
    return (units * size) / REFERENCE_FONT_SIZE;
}

