function normalizePrompt(prompt) {
    return String(prompt || '').toLowerCase().replace(/ё/g, 'е');
}

function detectGenre(prompt) {
    const text = normalizePrompt(prompt);
    let best = { id: 'arcade', score: 0 };
    for (const recipe of GENRE_RECIPES) {
        let score = 0;
        for (const keyword of recipe.keywords) {
            if (text.includes(normalizePrompt(keyword))) score += keyword.length >= 6 ? 3 : 2;
        }
        if (score > best.score) best = { id: recipe.id, score };
    }
    return best.id;
}

function getGenreRecipe(id) {
    return GENRE_RECIPES.find((recipe) => recipe.id === id) || GENRE_RECIPES.find((recipe) => recipe.id === 'arcade');
}

function buildDesignBrief(prompt, platform = 'pc') {
    const recipe = getGenreRecipe(detectGenre(prompt));
    const lines = [
        '=== БРИФ ГЕЙМДИЗАЙНЕРА ===',
        `Жанр: ${recipe.title}. Ядро: ${recipe.core}`,
        'Глубина (реализуй всё, а не только базовый цикл):',
        ...recipe.depth.map((item) => '- ' + item),
        VISUAL_SYSTEM,
        UX_CONTRACT,
        TECH_CONTRACT,
        `Платформа: ${platform === 'mobile' ? 'телефон (touch/pointer)' : 'ПК (мышь/клавиатура)'}.`,
        'Идея пользователя важнее рецепта: сохрани её тему, персонажей и фантазию, используй рецепт только как каркас качества.'
    ];
    return lines.join('\n');
}

